function translateValue(language: Language, key: string, fallback?: string): string {
  const runtimeValue = language === 'ar'
    ? runtimeArabicPhrases[key] ?? (fallback ? runtimeArabicPhrases[fallback] : undefined)
    : undefined;

  return runtimeValue
    ?? supplementalTranslations[language]?.[key]
    ?? dictionaryOverrides[language]?.[key]
    ?? dictionaries[language][key]
    ?? (fallback ? supplementalTranslations[language]?.[fallback] ?? dictionaryOverrides[language]?.[fallback] ?? dictionaries[language][fallback] ?? fallback : undefined)
    ?? key;
}

interface I18nContextValue {
  language: Language;
  direction: 'ltr' | 'rtl';
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

const languageStorageKey = 'crm_language';
const settingsStorageKey = 'medical-crm-settings-v1';

function isSupportedLanguage(value: unknown): value is Language {
  return value === 'ar' || value === 'en';
}

function readSettingsDefaultLanguage(): Language | null {
  if (typeof window === 'undefined') return null;

  try {
    const saved = window.localStorage.getItem(settingsStorageKey);
    if (!saved) return null;
    const parsed = JSON.parse(saved) as { defaultLanguage?: unknown };
    return isSupportedLanguage(parsed.defaultLanguage) ? parsed.defaultLanguage : null;
  } catch {
    return null;
  }
}

function initialLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  const settingsLanguage = readSettingsDefaultLanguage();
  if (settingsLanguage) return settingsLanguage;
  const stored = window.localStorage.getItem(languageStorageKey);
  return isSupportedLanguage(stored) ? stored : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);
  const direction = language === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    window.localStorage.setItem(languageStorageKey, language);
  }, [direction, language]);


  const value = useMemo<I18nContextValue>(() => ({
    language,
    direction,
    setLanguage: setLanguageState,
    toggleLanguage: () => setLanguageState((current) => current === 'en' ? 'ar' : 'en'),
    t: (key, fallback) => translateValue(language, key, fallback),
  }), [direction, language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}




